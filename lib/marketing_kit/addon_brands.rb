# frozen_string_literal: true

require "json"

module MarketingKit
  # The brand table the Studio Sheets add-on (addons/studio-sheets) styles a sheet
  # from. The add-on cannot read a kit spec (specs live in Drive, private), so this
  # renders the public part of each spec, the colours, the font and the title's
  # alignment, into addons/studio-sheets/src/Brands.js, from the same
  # SheetTemplate maths the drawer uses. Nothing else in a spec goes into the
  # table: a spec also holds contact details, and the repo is public.
  #
  #   script/marketing_kit/addon_brands.rb mi/kit.yml ms/kit.yml cw/kit.yml tm/kit.yml
  module AddonBrands
    OUT = "addons/studio-sheets/src/Brands.js"

    # One brand's row: the three head sections (top, low), the title colour, the
    # headline colour, the title's alignment and the font family.
    def self.entry(spec)
      template = SheetTemplate.new(spec)
      {
        name: spec.name,
        font: spec.fonts[:family],
        title: template.title_colour,
        headline: spec.colour(:title),
        titleAlign: template.title_align,
        sections: template.sections.map { |s| { top: s.top, low: s.low } }
      }
    end

    # The drawer's fixed colours, from SheetTemplate: white head text, the
    # archived row's grey text on the light fill.
    def self.sheet_colours
      { white: SheetTemplate::WHITE, grey: SheetTemplate::GREY, light: SheetTemplate::LIGHT }
    end

    # Brands.js for the given specs, keyed by short code (MI, MS, CW, TM), sorted.
    def self.render(specs)
      brands = specs.sort_by(&:short).to_h { |spec| [spec.short, entry(spec)] }
      <<~JS
        // GENERATED by script/marketing_kit/addon_brands.rb from the kit specs.
        // Do not edit by hand: regenerate it (see addons/studio-sheets/README.md).
        // The values come from MarketingKit::SheetTemplate, the drawer's own maths.

        var STUDIO_BRANDS = #{JSON.pretty_generate(brands)};

        var STUDIO_SHEET_COLOURS = #{JSON.pretty_generate(sheet_colours)};
      JS
    end
  end
end
