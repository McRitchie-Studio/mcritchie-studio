# frozen_string_literal: true

require "fileutils"
require_relative "../../lib/node_tooling_link"

# DeskNodeModules: a new desk borrows the primary checkout's node_modules instead of
# installing its own, when (and only when) that is provably the same install.
#
# WHY. Since the node-tooling adoption (2026-10-27) every desk needs node_modules for
# bin/test-js, Playwright and the fast-check pre-flight, and a cold `npm ci` per desk
# is the slowest step of a desk's first gate. The primary already holds the install.
#
# THE RULE. Link only when the desk's package-lock.json is byte-for-byte the primary's,
# and the primary's node_modules is a real, installed directory (never a link itself).
# A lock that differs gets the desk's own `npm ci`. Never on Heroku or CI: CI installs
# from its own lock, and a link there would hold a laptop path (NodeToolingLink.heroku?
# is the one Heroku test, shared with `node_tooling:link`).
#
# THE SHAPE: a link FARM, not one directory link. The desk gets a real node_modules
# directory whose top-level entries are symlinks to the primary's entries, except the
# DESK_LOCAL ones. Two measured reasons the single `node_modules -> primary` link is
# wrong here:
#
#   1. `node_tooling:link` writes node_modules/.studio-engine -> the gem THIS checkout
#      bundles. Through a directory link that write lands in the primary, so
#      NodeToolingLink refuses a shared node_modules unless the primary already links
#      the same gem, and the primary had no link at all (2026-10-28): bin/test-js and
#      fast-check would go red in every shared desk. In a farm .studio-engine is the
#      desk's own entry, and each desk links whichever engine it bundles.
#   2. Every deleter that walks the desk (`git worktree remove`, FileUtils.rm_rf, npm
#      ci's own wipe) unlinks a symlinked ENTRY without following it. A symlinked
#      node_modules ITSELF is one `rm -rf node_modules/` away from the primary's tree.
#
# THE RECLAIM GUARD. release! unlinks every top-level symlink (and a legacy whole-
# directory link) before a teardown deletes anything, so no deleter ever meets a link
# into the primary. It is unlink-only: it never recurses and never follows a link.
module DeskNodeModules
  NODE_MODULES = "node_modules"
  LOCK = "package-lock.json"
  MANIFEST = "package.json"
  # Entries a desk owns even when it borrows the rest: the engine tooling link is
  # per-checkout by design (lib/node_tooling_link.rb).
  DESK_LOCAL = %w[.studio-engine].freeze
  NPM_CI = %w[npm ci --no-audit --no-fund].freeze

  Plan = Struct.new(:action, :reason, :source, keyword_init: true) do
    def link? = action == :link
    def install? = action == :install
    def skip? = action == :skip
  end

  module_function

  # What `new` should do for this desk: :link (borrow the primary's entries),
  # :install (the desk's own `npm ci`) or :skip. Reads the filesystem; writes nothing.
  def plan(desk:, primary:, env: ENV)
    desk = File.expand_path(desk.to_s)
    primary = File.expand_path(primary.to_s)
    return skip("Heroku (DYNO/STACK set): nothing there runs Playwright or node:test") if NodeToolingLink.heroku?(env)
    return skip("CI: the workflow installs from its own lock") if ci?(env)
    return skip("no #{MANIFEST}") unless File.file?(File.join(desk, MANIFEST))

    desk_modules = File.join(desk, NODE_MODULES)
    return skip("#{NODE_MODULES} already present") if File.symlink?(desk_modules) || File.exist?(desk_modules)
    return skip("no #{LOCK} (npm ci needs one)") unless File.file?(File.join(desk, LOCK))
    return skip("the desk is the primary checkout") if same_dir?(desk, primary)

    primary_lock = File.join(primary, LOCK)
    return install("the primary has no #{LOCK}") unless File.file?(primary_lock)
    return install("#{LOCK} differs from the primary's") unless FileUtils.compare_file(File.join(desk, LOCK), primary_lock)

    source = File.join(primary, NODE_MODULES)
    return install("the primary's #{NODE_MODULES} is itself a link") if File.symlink?(source)
    return install("the primary has no installed #{NODE_MODULES}") unless File.directory?(source)

    Plan.new(action: :link, reason: "#{LOCK} matches the primary's", source: source)
  end

  # Build the farm: desk/node_modules as a real directory, each primary entry but the
  # DESK_LOCAL ones linked in by absolute path. Returns the linked entry names. On any
  # failure the half-built farm is released (links only) and the error re-raised.
  def link!(desk:, source:)
    target = File.join(File.expand_path(desk.to_s), NODE_MODULES)
    Dir.mkdir(target)
    linked = []
    Dir.children(source).sort.each do |name|
      next if DESK_LOCAL.include?(name)

      File.symlink(File.join(source, name), File.join(target, name))
      linked << name
    end
    linked
  rescue SystemCallError
    release!(desk)
    raise
  end

  # THE RECLAIM GUARD. Unlink every link the desk holds into another tree, before any
  # deleter runs: a whole node_modules link (a hand-made desk), else each top-level
  # symlinked entry. Unlink-only: never recurses, never follows. Returns the removed
  # paths. A desk with no node_modules, or a fully installed one, removes nothing.
  def release!(desk)
    modules = File.join(File.expand_path(desk.to_s), NODE_MODULES)
    if File.symlink?(modules)
      File.unlink(modules)
      return [modules]
    end
    return [] unless File.directory?(modules)

    Dir.children(modules).sort.filter_map do |name|
      entry = File.join(modules, name)
      next unless File.symlink?(entry)

      File.unlink(entry)
      entry
    end
  end

  def ci?(env)
    value = env["CI"].to_s.strip.downcase
    return true if env["GITHUB_ACTIONS"].to_s == "true"

    !value.empty? && value != "false" && value != "0"
  end

  def same_dir?(a, b)
    File.realpath(a) == File.realpath(b)
  rescue SystemCallError
    a == b
  end

  def skip(reason) = Plan.new(action: :skip, reason: reason)
  def install(reason) = Plan.new(action: :install, reason: reason)
end
