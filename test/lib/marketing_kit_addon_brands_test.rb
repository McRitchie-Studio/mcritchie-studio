# frozen_string_literal: true

require "test_helper"
require_relative "../support/marketing_kit_fixtures"

# [unit] MarketingKit::AddonBrands: the brand table the Studio Sheets add-on styles
# a sheet from carries the drawer's own colours (SheetTemplate), and nothing else
# from the spec.
class MarketingKitAddonBrandsTest < ActiveSupport::TestCase
  include MarketingKitFixtures

  test "a brand's row is the drawer's sections, title, headline, alignment and font" do
    load_kit do |spec|
      template = MarketingKit::SheetTemplate.new(spec)
      entry = MarketingKit::AddonBrands.entry(spec)

      assert_equal template.sections.map { |s| { top: s.top, low: s.low } }, entry[:sections]
      assert_equal template.title_colour, entry[:title]
      assert_equal spec.colour(:title), entry[:headline]
      assert_equal template.title_align, entry[:titleAlign]
      assert_equal spec.fonts[:family], entry[:font]
      assert_equal %i[name font title headline titleAlign sections], entry.keys
    end
  end

  test "Brands.js keys brands by short code and carries the drawer's fixed colours" do
    load_kit do |spec|
      js = MarketingKit::AddonBrands.render([spec])
      brands = JSON.parse(js[/var STUDIO_BRANDS = (\{.*?\n\});/m, 1])
      colours = JSON.parse(js[/var STUDIO_SHEET_COLOURS = (\{.*?\n\});/m, 1])

      assert_equal [spec.short], brands.keys
      assert_equal MarketingKit::SheetTemplate.new(spec).sections.first.top, brands[spec.short]["sections"][0]["top"]
      assert_equal({ "white" => "#FFFFFF", "grey" => "#5A6675", "light" => "#F3F5F8" }, colours)
      assert_match(/\A\/\/ GENERATED by script\/marketing_kit\/addon_brands.rb/, js)
    end
  end

  test "the table never carries a spec's contact details" do
    load_kit do |spec|
      js = MarketingKit::AddonBrands.render([spec])
      assert_no_match(/@/, js, "no email address")
      assert_no_match(/https?:/, js, "no link")
      assert_not_includes js, spec.tagline
    end
  end

  test "the committed table holds the four brands, each complete" do
    js = File.read(Rails.root.join(MarketingKit::AddonBrands::OUT))
    brands = JSON.parse(js[/var STUDIO_BRANDS = (\{.*?\n\});/m, 1])
    assert_equal %w[CW MI MS TM], brands.keys
    brands.each do |code, b|
      assert_equal 3, b["sections"].size, code
      b["sections"].each do |s|
        assert_operator MarketingKit::SheetTemplate.contrast_with_white(s["low"]), :>=, MarketingKit::SheetTemplate::MIN_CONTRAST, code
      end
      assert_includes %w[center bottom], b["titleAlign"], code
    end
  end
end
