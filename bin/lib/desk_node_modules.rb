# frozen_string_literal: true

require "fileutils"
require "open3"
require "shellwords"
require_relative "bounded_command"
require_relative "../../lib/node_tooling_link"

# DeskNodeModules: a new desk borrows the primary checkout's node_modules instead of
# installing its own, when (and only when) that is provably the same install.
#
# WHY. Since the node-tooling adoption (2026-10-27) every desk needs node_modules for
# bin/test-js, Playwright and the fast-check pre-flight, and a cold `npm ci` per desk
# is the slowest step of a desk's first gate. The primary already holds the install.
#
# THE RULE. Link only when the desk's package-lock.json is byte-for-byte the primary's
# and the primary's node_modules is a FINISHED install: a real directory (never a link
# itself) holding npm's hidden lockfile, node_modules/.package-lock.json, which npm
# writes last. A lock that differs gets the desk's own `npm ci`, bounded by a deadline.
# Never on Heroku or CI: CI installs from its own lock, and a link there would hold a
# laptop path (NodeToolingLink.heroku? is the one Heroku test, shared with
# `node_tooling:link`). The links are a SNAPSHOT of the primary when the desk was cut;
# `npm ci` in the desk is always the repair.
#
# THE SHAPE: a link FARM, never a directory npm writes into. The desk's node_modules is
# a real directory. Each PACKAGE is linked: a top-level package directory, and one level
# down inside each `@scope` directory, which is a real directory in the desk. `.bin` is
# a real directory too, its entries recreated as links. Never linked (DESK_LOCAL):
# `.package-lock.json` (npm rewrites it on every install), `.cache` (tools write there)
# and `.studio-engine` (each checkout links the engine it bundles).
#
# WHY NOT ONE `node_modules -> primary` LINK, or a linked `@scope` or `.bin` directory.
# npm writes inside every directory it walks: `npm install` renames a package it
# replaces to `@scope/.name-xxxx`, rewrites `.package-lock.json` and unlinks `.bin`
# entries on uninstall. Through a linked directory each of those writes lands in the
# PRIMARY (reproduced with npm 10.8.2: a desk's install stripped `@playwright/test`
# from the primary). With only packages linked, npm's renames and removals act on the
# desk's own link, never on what it points at; test/lib/desk_node_modules_test.rb runs
# real installs to prove the primary stays byte-identical. Scripts are the exception a
# farm alone does not cover (THE SCRIPT GUARD, below). And `node_tooling:link` refuses a
# node_modules shared whole (lib/node_tooling_link.rb).
#
# THE RECLAIM GUARD. release! unlinks every link the desk holds into the primary (a
# legacy whole-directory link, top-level links, and links one level down in `@scope`
# and `.bin`) before a teardown deletes anything. Unlink-only: it never follows a link.
# What it leaves (empty `@scope` and `.bin` directories, the desk's `.cache`) is a HUSK:
# when the teardown stops after release! (a dirty desk makes `git worktree remove`
# refuse), the next `new` on that desk treats the husk as absent and links again.
#
# THE SCRIPT GUARD. npm does not write through a package link, but it RUNS through one:
# `npm rebuild` runs each package's install scripts with the package's real directory
# as cwd, so in a farm they ran inside the primary's node_modules. Before link! makes
# any link it writes the desk's `.npmrc` with `script-shell` set to a guard kept in the
# desk's own git dir: every lifecycle script npm starts goes through the guard, which
# runs it only when its cwd is inside the desk and otherwise refuses, naming itself.
# After `npm ci` replaces the links every package dir is the desk's, so the guard never
# refuses again. A desk links only where the guard is safe to write: no `.npmrc` of its
# own, and `.npmrc` ignored by git there (an untracked one would make the desk dirty).
#
# A FAILED INSTALL. install! discards the partial node_modules a failed or killed
# `npm ci` leaves (links first, then the desk's own directory), so the next plan
# retries instead of skipping a desk that has "node_modules already present".
module DeskNodeModules
  NODE_MODULES = "node_modules"
  LOCK = "package-lock.json"
  HIDDEN_LOCK = ".package-lock.json"
  MANIFEST = "package.json"
  BIN = ".bin"
  # Entries a desk owns even when it borrows the rest.
  DESK_LOCAL = [HIDDEN_LOCK, ".cache", ".studio-engine"].freeze
  NPM_CI = %w[npm ci --no-audit --no-fund].freeze
  # Seconds a desk's own `npm ci` may take before its process group is killed, so a hung
  # install cannot hang `new` (and `bin/task begin` behind it).
  NPM_CI_DEADLINE = 600
  DEADLINE_ENV = "AGENT_WORKTREE_NPM_CI_DEADLINE"
  NPMRC = ".npmrc"
  # The guard's file name inside the desk's git dir, and the line that marks a
  # `.npmrc` as the one link! wrote (a resume may reuse it; any other is the desk's own).
  GUARD = "desk-npm-script-shell"
  NPMRC_MARK = "# bin/lib/desk_node_modules.rb: the script guard (see THE SCRIPT GUARD)"

  # A bad AGENT_WORKTREE_NPM_CI_DEADLINE: zero, negative or not a whole number.
  class InvalidDeadline < ArgumentError; end

  Plan = Struct.new(:action, :reason, :source, keyword_init: true) do
    def link? = action == :link
    def install? = action == :install
    def skip? = action == :skip
  end

  module_function

  # What `new` should do for this desk: :link (borrow the primary's packages),
  # :install (the desk's own `npm ci`) or :skip. Reads the filesystem; writes nothing.
  def plan(desk:, primary:, env: ENV)
    desk = File.expand_path(desk.to_s)
    primary = File.expand_path(primary.to_s)
    return skip("Heroku (DYNO/STACK set): nothing there runs Playwright or node:test") if NodeToolingLink.heroku?(env)
    return skip("CI: the workflow installs from its own lock") if ci?(env)
    return skip("no #{MANIFEST}") unless File.file?(File.join(desk, MANIFEST))

    desk_modules = File.join(desk, NODE_MODULES)
    if (File.symlink?(desk_modules) || File.exist?(desk_modules)) && !husk?(desk_modules)
      return skip("#{NODE_MODULES} already present")
    end
    return skip("no #{LOCK} (npm ci needs one)") unless File.file?(File.join(desk, LOCK))
    return skip("the desk is the primary checkout") if same_dir?(desk, primary)

    primary_lock = File.join(primary, LOCK)
    return install("the primary has no #{LOCK}") unless File.file?(primary_lock)
    return install("#{LOCK} differs from the primary's") unless FileUtils.compare_file(File.join(desk, LOCK), primary_lock)

    source = File.join(primary, NODE_MODULES)
    return install("the primary's #{NODE_MODULES} is itself a link") if File.symlink?(source)
    return install("the primary has no installed #{NODE_MODULES}") unless File.directory?(source)
    unless File.file?(File.join(source, HIDDEN_LOCK))
      return install("the primary's install is unfinished (no #{NODE_MODULES}/#{HIDDEN_LOCK})")
    end

    unguardable = guard_refusal(desk)
    return install(unguardable) if unguardable

    Plan.new(action: :link, reason: "#{LOCK} matches the primary's", source: source)
  end

  # A released farm: a real node_modules directory holding nothing but desk-local
  # entries and EMPTY `@scope`/`.bin` directories. It holds no package, so linking or
  # installing over it loses nothing.
  def husk?(modules)
    return false if File.symlink?(modules) || !File.directory?(modules)

    Dir.children(modules).all? do |name|
      entry = File.join(modules, name)
      next true if DESK_LOCAL.include?(name) && !File.symlink?(entry)

      container?(name, entry) && Dir.empty?(entry)
    end
  end

  # Why the script guard cannot be written in this desk, or nil when it can.
  def guard_refusal(desk)
    npmrc = File.join(desk, NPMRC)
    if File.symlink?(npmrc) || (File.exist?(npmrc) && !own_npmrc?(npmrc))
      return "the desk has its own #{NPMRC}, so the npm script guard cannot be set"
    end
    return "#{NPMRC} is not ignored by git in the desk, so the npm script guard would dirty it" unless git_ignored?(desk, NPMRC)
    return "the desk has no git dir to hold the npm script guard" unless git_dir(desk)

    nil
  end

  def own_npmrc?(npmrc) = File.file?(npmrc) && File.read(npmrc).lines.first.to_s.chomp == NPMRC_MARK

  def git_ignored?(desk, path)
    _out, status = Open3.capture2e("git", "-C", desk, "check-ignore", "-q", "--", path)
    status.success?
  rescue SystemCallError
    false
  end

  # The desk's own git dir: `.git` itself, or the per-worktree dir a `.git` file names.
  # Pure filesystem reads; nil when there is none.
  def git_dir(desk)
    dot = File.join(desk, ".git")
    return dot if File.directory?(dot) && !File.symlink?(dot)
    return nil unless File.file?(dot)

    line = File.read(dot)[/\Agitdir: (.+)$/, 1]
    return nil unless line

    dir = File.expand_path(line.strip, desk)
    File.directory?(dir) ? dir : nil
  end

  # Write the guard and the `.npmrc` that names it. Called by link! before its first
  # link, so a farm never exists without the guard. Returns the guard's path.
  def write_guard!(desk)
    dir = git_dir(desk) or raise Errno::ENOENT, "#{desk}/.git (the npm script guard lives in the desk's git dir)"
    guard = File.join(dir, GUARD)
    File.write(guard, guard_script(File.realpath(desk)))
    File.chmod(0o755, guard)
    File.write(File.join(desk, NPMRC), "#{NPMRC_MARK}\nscript-shell=#{guard}\n")
    guard
  end

  # The guard: run the script with /bin/sh when npm started it inside the desk, else
  # refuse. npm calls a script-shell as `<shell> -c <command>` with the package's
  # directory as cwd; `pwd -P` resolves a link, so a linked package reads as the primary.
  def guard_script(desk_real)
    <<~SH
      #!/bin/sh
      # Written by bin/lib/desk_node_modules.rb (THE SCRIPT GUARD) for one desk.
      here=$(pwd -P)
      case "$here/" in
        #{Shellwords.escape(desk_real)}/*) exec /bin/sh "$@" ;;
      esac
      # Single quotes: the backticks below are text, never a command substitution.
      echo "desk-node-modules: refused an npm lifecycle script in $here:" 'it is a package of the PRIMARY checkout, linked into this desk. Run `npm ci` in the desk first: it replaces every link with a real install.' >&2
      exit 1
    SH
  end

  # Build the farm. Returns the linked paths, relative to node_modules. On any failure
  # the half-built farm is released (links only) and the error re-raised.
  def link!(desk:, source:)
    desk = File.expand_path(desk.to_s)
    target = File.join(desk, NODE_MODULES)
    write_guard!(desk)
    # A husk (a farm a refused teardown released) is reused: its directories are empty.
    FileUtils.mkdir_p(target)
    linked = []
    Dir.children(source).sort.each do |name|
      next if DESK_LOCAL.include?(name)

      from = File.join(source, name)
      if container?(name, from)
        FileUtils.mkdir_p(File.join(target, name))
        Dir.children(from).sort.each do |child|
          link_entry(File.join(from, child), File.join(target, name, child), bin: name == BIN)
          linked << File.join(name, child)
        end
      else
        File.symlink(from, File.join(target, name))
        linked << name
      end
    end
    linked
  rescue SystemCallError
    release!(desk)
    raise
  end

  # A `.bin` entry that is a RELATIVE link (`../playwright/cli.js`) is recreated as the
  # same relative link, so it resolves through the desk's own package link; anything
  # else links to the primary's entry by absolute path.
  def link_entry(from, to, bin:)
    if bin && File.symlink?(from) && !File.readlink(from).start_with?("/")
      File.symlink(File.readlink(from), to)
    else
      File.symlink(from, to)
    end
  end

  # A directory npm writes INTO rather than replaces: a scope or `.bin`.
  def container?(name, path)
    (name.start_with?("@") || name == BIN) && File.directory?(path) && !File.symlink?(path)
  end

  # THE RECLAIM GUARD. Unlink every link before any deleter runs: a whole node_modules
  # link (a hand-made desk), else each top-level link and each link one level down in a
  # real `@scope` or `.bin` directory. Unlink-only, never follows. Returns the removed
  # paths. A desk with no node_modules, or a fully installed one, removes nothing.
  def release!(desk)
    modules = File.join(File.expand_path(desk.to_s), NODE_MODULES)
    if File.symlink?(modules)
      File.unlink(modules)
      return [modules]
    end
    return [] unless File.directory?(modules)

    Dir.children(modules).sort.flat_map do |name|
      entry = File.join(modules, name)
      if File.symlink?(entry)
        File.unlink(entry)
        [entry]
      elsif container?(name, entry)
        Dir.children(entry).sort.filter_map do |child|
          inner = File.join(entry, child)
          next unless File.symlink?(inner)

          File.unlink(inner)
          inner
        end
      else
        []
      end
    end
  end

  # The desk's own `npm ci`, killed with its whole process group at the deadline.
  # Returns the BoundedCommand::Result; output streams to +stream+ as it arrives.
  def npm_ci!(desk, deadline: NPM_CI_DEADLINE, stream: $stdout, argv: NPM_CI)
    BoundedCommand.run({}, argv, deadline: deadline, pgroup: true, stream: stream,
                                 chdir: File.expand_path(desk.to_s), in: File::NULL, err: %i[child out])
  end

  # The desk's own `npm ci`, bounded; on a failure or a kill, the partial node_modules it
  # leaves is discarded (discard!) so the next plan sees no node_modules and retries.
  # Returns the BoundedCommand::Result.
  def install!(desk, deadline: NPM_CI_DEADLINE, stream: $stdout, argv: NPM_CI)
    result = npm_ci!(desk, deadline: deadline, stream: stream, argv: argv)
    discard!(desk) unless result.success?
    result
  end

  # Remove the desk's node_modules: the reclaim guard first (every link into the
  # primary is unlinked, never followed), then the desk's own directory, named without
  # a trailing slash so the delete cannot follow a link either. Returns whether it is gone.
  def discard!(desk)
    modules = File.join(File.expand_path(desk.to_s), NODE_MODULES)
    release!(desk)
    FileUtils.rm_rf(modules)
    !File.symlink?(modules) && !File.exist?(modules)
  end

  # The npm ci deadline, in seconds, from AGENT_WORKTREE_NPM_CI_DEADLINE. Unset or blank
  # is the default; a bad value is reported through +warn+ and also gets the default.
  def npm_ci_deadline(env = ENV, warn: ->(message) { Kernel.warn(message) })
    parse_deadline(env[DEADLINE_ENV])
  rescue InvalidDeadline => e
    warn.call("#{e.class.name}: #{e.message}; using the default #{NPM_CI_DEADLINE}s")
    NPM_CI_DEADLINE
  end

  # Raises InvalidDeadline unless +raw+ is unset, blank or a positive whole number.
  def parse_deadline(raw)
    text = raw.to_s.strip
    return NPM_CI_DEADLINE if text.empty?
    raise InvalidDeadline, "#{DEADLINE_ENV} must be a positive whole number of seconds, got #{raw.inspect}" unless text.match?(/\A\d+\z/)

    value = Integer(text, 10)
    raise InvalidDeadline, "#{DEADLINE_ENV} must be a positive whole number of seconds, got #{raw.inspect}" unless value.positive?

    value
  end

  def ci?(env)
    return true if env["GITHUB_ACTIONS"].to_s == "true"

    value = env["CI"].to_s.strip.downcase
    !value.empty? && value != "false" && value != "0"
  end

  def same_dir?(a, b)
    File.realpath(a) == File.realpath(b)
  rescue SystemCallError
    a == b
  end

  def skip(reason) = Plan.new(action: :skip, reason: reason)
  def install(reason) = Plan.new(action: :install, reason: reason)
end
