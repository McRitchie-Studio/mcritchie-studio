# frozen_string_literal: true

# THE SOP REGISTRY, generated from the SOP files.
#
# An SOP is invoked by NAME: Alex McRitchie says `clean-up` and the agent runs
# `bin/sop clean-up`, which resolves that phrase through `entries` below to a file.
# The table in docs/agents/start-here.md is generated here too. It used to be a
# hand-kept copy of what the disk already says, and AGENTS.md carried a second copy
# until the boot budget moved it out (task boot-budget-and-sop-resolver). So a new SOP
# file is registered by existing:
#
#   docs/agents/agents/<soul>/HEARTBEAT.md   `<Soul> Heartbeat`, owned by that soul
#   docs/agents/agents/<soul>/sops/<sop>.md  `<sop>`, owned by that soul
#   docs/agents/modules/<sop>.md             `<sop>`, Shared, when it carries a marker
#
# The invocation is the file name, the owner is the directory, and the one thing the path
# cannot say, a short summary, rides in a marker line under the file's H1:
#
#   <!-- registry: the summary Start Here prints -->
#   <!-- registry (role SOP): the primary reviewer's own steps -->
#
# The marker is optional for a soul's files (they are SOPs by where they live) and is
# what makes a module an SOP. bin/sop-registry writes the generated block and checks
# it; test/docs/sop_registry_generated_test.rb holds the committed block to it.
module SopRegistry
  Entry = Struct.new(:invocation, :owner, :path, :note, :summary, :kind, keyword_init: true)

  MARKER = /^<!-- registry(?: \((?<note>[^)]+)\))?(?::\s*(?<summary>.*?))?\s*-->\s*$/
  START_HERE_PATH = "docs/agents/start-here.md"
  BLOCK = "sop-registry"

  module_function

  def owner_for(dir) = dir.split("_").map(&:capitalize).join(" ")

  def marker(text) = text.each_line.lazy.filter_map { |line| MARKER.match(line) }.first

  # Every registry entry under `root`, in table order: each soul alphabetically (its
  # heartbeat, then its SOPs), then the shared SOPs.
  def entries(root)
    souls = Dir.glob(File.join(root, "docs/agents/agents/*")).select { |dir| File.directory?(dir) }.sort
    soul_entries = souls.flat_map do |dir|
      soul = File.basename(dir)
      owner = owner_for(soul)
      heartbeat = File.join(dir, "HEARTBEAT.md")
      rows = []
      rows << entry(root, heartbeat, "#{owner} Heartbeat", owner, :heartbeat) if File.file?(heartbeat)
      rows + Dir.glob(File.join(dir, "sops", "*.md")).sort.map do |path|
        entry(root, path, File.basename(path, ".md"), owner, :soul)
      end
    end
    shared = Dir.glob(File.join(root, "docs/agents/modules/*.md")).sort.filter_map do |path|
      next unless marker(File.read(path))

      entry(root, path, File.basename(path, ".md"), "Shared", :shared)
    end
    soul_entries + shared
  end

  def entry(root, path, invocation, owner, kind)
    found = marker(File.read(path))
    Entry.new(invocation: invocation, owner: owner, kind: kind,
              path: path.delete_prefix("#{root}/"),
              note: found && found[:note], summary: found && found[:summary].to_s.strip.then { |s| s.empty? ? nil : s })
  end

  # A name folded for a forgiving match: case, and the space, hyphen or underscore
  # between words, do not count. `mason heartbeat` finds `Mason Heartbeat`.
  def fold(name) = name.to_s.downcase.gsub(/[\s_-]+/, "-")

  # The entry `name` invokes: the exact invocation first, then the folded one.
  def resolve(entries, name)
    entries.find { |e| e.invocation == name } ||
      entries.find { |e| fold(e.invocation) == fold(name) }
  end

  # Up to five registered names close to `name`: spelling neighbours, then names that
  # contain it or that it contains.
  def suggest(entries, name)
    require "did_you_mean"
    names = entries.map(&:invocation)
    by_fold = names.to_h { |n| [fold(n), n] }
    key = fold(name)
    spelled = DidYouMean::SpellChecker.new(dictionary: by_fold.keys).correct(key)
    within = key.empty? ? [] : by_fold.keys.select { |k| k.include?(key) || key.include?(k) }
    (spelled + within).uniq.first(5).map { |k| by_fold.fetch(k) }
  end

  # The Start Here rows: a soul SOP reads `<Soul> \`<sop>\` SOP`, a heartbeat
  # `\`<Soul> Heartbeat\` launcher`, a shared SOP `\`<sop>\``, each with its summary.
  def start_here_table(entries)
    rows = entries.map do |e|
      label = case e.kind
              when :heartbeat then "`#{e.invocation}` launcher"
              when :soul then "#{e.owner} `#{e.invocation}` SOP"
              else "`#{e.invocation}`"
              end
      label = "#{label} (#{e.summary})" if e.summary
      "| #{label} | `mcritchie-studio/#{e.path}` |"
    end
    ["| SOP or heartbeat | Read |", "|------------------|------|", *rows].join("\n")
  end

  def begin_marker = "<!-- BEGIN #{BLOCK}: generated by bin/sop-registry from the SOP files; edit those, then run bin/sop-registry --write -->"
  def end_marker = "<!-- END #{BLOCK} -->"

  # `text` with its generated block replaced by `table`. Raises when the markers are
  # missing, so a doc that lost its block is loud rather than silently unregistered.
  def splice(text, table, path)
    start = text.index(begin_marker)
    stop = text.index(end_marker)
    raise ArgumentError, "#{path} has no #{BLOCK} block (#{begin_marker} … #{end_marker})" unless start && stop && start < stop

    text[0...start] + begin_marker + "\n" + table + "\n" + text[stop..]
  end

  # { relative path => [current text, generated text] } for the generated doc.
  def renders(root)
    list = entries(root)
    { START_HERE_PATH => start_here_table(list) }.to_h do |rel, table|
      current = File.read(File.join(root, rel))
      [rel, [current, splice(current, table, rel)]]
    end
  end

  # The generated docs whose committed text is not what the generator writes.
  def stale(root) = renders(root).filter_map { |rel, (current, wanted)| rel unless current == wanted }

  def write!(root)
    renders(root).each { |rel, (_current, wanted)| File.write(File.join(root, rel), wanted) }
  end
end
