# frozen_string_literal: true

# [unit] bin/lib/desk_node_modules.rb: a desk borrows the primary's node_modules only
# when package-lock.json matches byte for byte, never on Heroku or CI, and a teardown
# never deletes through a link into the primary's tree.
#
# Every tree here is a temp dir: a fake "primary" and a fake "desk". Nothing reads or
# writes a real checkout. Run directly:
#   ruby -Itest test/lib/desk_node_modules_test.rb
require "minitest/autorun"
require "fileutils"
require "open3"
require "tmpdir"
require_relative "../../bin/lib/desk_node_modules"

class DeskNodeModulesTest < Minitest::Test
  LOCK = %({"name":"hub","lockfileVersion":3,"packages":{"node_modules/playwright":{"version":"1.56.1"}}}\n)

  def setup
    @root = Dir.mktmpdir("desk-node-modules")
    @primary = File.join(@root, "primary")
    @desk = File.join(@root, "desk")
    FileUtils.mkdir_p([@primary, @desk])
    [@primary, @desk].each do |tree|
      File.write(File.join(tree, "package.json"), %({"name":"hub"}\n))
      File.write(File.join(tree, "package-lock.json"), LOCK)
    end
    # The primary's install: a package dir, a scope dir, .bin, npm's hidden lockfile,
    # and the primary's own engine tooling link (which a desk must never borrow).
    @modules = File.join(@primary, "node_modules")
    @sentinel = File.join(@modules, "playwright", "index.js")
    FileUtils.mkdir_p([File.dirname(@sentinel), File.join(@modules, "@playwright", "test"), File.join(@modules, ".bin")])
    File.write(@sentinel, "module.exports = 'primary'\n")
    File.write(File.join(@modules, "@playwright", "test", "index.js"), "// test\n")
    File.write(File.join(@modules, ".package-lock.json"), LOCK)
    @gem = File.join(@root, "gems", "studio-engine-0.116.0")
    FileUtils.mkdir_p(@gem)
    File.symlink(@gem, File.join(@modules, ".studio-engine"))
  end

  def teardown
    FileUtils.rm_rf(@root)
  end

  def plan(env: {}) = DeskNodeModules.plan(desk: @desk, primary: @primary, env: env)

  def primary_intact!
    assert File.file?(@sentinel), "the primary's node_modules must survive: #{@sentinel} is gone"
    assert_equal "module.exports = 'primary'\n", File.read(@sentinel)
    assert File.file?(File.join(@modules, "@playwright", "test", "index.js"))
    assert File.symlink?(File.join(@modules, ".studio-engine")), "the primary's own engine link survives"
    assert Dir.exist?(@gem), "nothing deleted through the engine link either"
  end

  # --- plan --------------------------------------------------------------------

  def test_a_matching_lock_plans_a_link_to_the_primary
    result = plan
    assert result.link?, result.reason
    assert_equal @modules, result.source
    refute File.exist?(File.join(@desk, "node_modules")), "plan writes nothing"
  end

  def test_a_lock_that_differs_by_one_byte_plans_npm_ci_and_writes_nothing
    File.write(File.join(@desk, "package-lock.json"), LOCK.sub("1.56.1", "1.56.2"))
    result = plan
    assert result.install?, result.reason
    assert_match(/differs from the primary's/, result.reason)
    refute File.exist?(File.join(@desk, "node_modules")), "no link for a differing lock"
  end

  def test_heroku_and_ci_never_link
    [{ "DYNO" => "web.1" }, { "STACK" => "heroku-24" }].each do |env|
      assert plan(env: env).skip?, "Heroku #{env.inspect} must never link"
      assert_match(/Heroku/, plan(env: env).reason)
    end
    assert plan(env: { "CI" => "true" }).skip?, "CI installs from its own lock"
    assert plan(env: { "GITHUB_ACTIONS" => "true" }).skip?, "an Actions runner is CI"
    assert plan(env: { "CI" => "false" }).link?, "CI=false is not CI"
  end

  def test_a_desk_with_no_manifest_or_no_lock_is_skipped
    File.delete(File.join(@desk, "package-lock.json"))
    assert plan.skip?, "npm ci needs a lock; nothing to compare either"
    File.delete(File.join(@desk, "package.json"))
    assert_match(/no package\.json/, plan.reason)
  end

  def test_an_existing_desk_node_modules_is_left_alone
    FileUtils.mkdir_p(File.join(@desk, "node_modules"))
    assert plan.skip?
    assert_match(/already present/, plan.reason)
  end

  def test_the_primary_with_no_install_or_no_lock_plans_npm_ci
    FileUtils.rm_rf(@modules)
    assert plan.install?, "nothing to borrow"
    File.delete(File.join(@primary, "package-lock.json"))
    assert_match(/primary has no package-lock\.json/, plan.reason)
  end

  def test_a_primary_whose_node_modules_is_itself_a_link_is_never_chained
    elsewhere = File.join(@root, "elsewhere")
    FileUtils.mv(@modules, elsewhere)
    File.symlink(elsewhere, @modules)
    assert plan.install?
    assert_match(/itself a link/, plan.reason)
  end

  def test_the_primary_is_never_planned_against_itself
    result = DeskNodeModules.plan(desk: @primary, primary: @primary, env: {})
    assert result.skip?, "the primary already has node_modules; it never links to itself"
  end

  # --- link! -------------------------------------------------------------------

  def test_link_builds_a_farm_of_entry_links_and_keeps_the_engine_link_desk_local
    linked = DeskNodeModules.link!(desk: @desk, source: @modules)
    farm = File.join(@desk, "node_modules")

    refute File.symlink?(farm), "the desk's node_modules is a real directory, never a link into the primary"
    assert File.directory?(farm)
    assert_equal %w[.bin .package-lock.json @playwright playwright], linked
    linked.each do |name|
      assert File.symlink?(File.join(farm, name))
      assert_equal File.join(@modules, name), File.readlink(File.join(farm, name))
    end
    assert_equal "module.exports = 'primary'\n", File.read(File.join(farm, "playwright", "index.js")), "resolves into the primary"
    refute File.exist?(File.join(farm, ".studio-engine")), "the engine tooling link is each checkout's own"

    # node_tooling:link in the desk now writes the DESK's entry, not the primary's.
    File.symlink(File.join(@root, "gems", "studio-engine-0.117.0"), File.join(farm, ".studio-engine"))
    assert_equal @gem, File.readlink(File.join(@modules, ".studio-engine")), "the primary's engine link is untouched"
  end

  # --- release!: the reclaim guard ---------------------------------------------

  def test_release_removes_only_the_links_and_never_the_primarys_files
    DeskNodeModules.link!(desk: @desk, source: @modules)
    removed = DeskNodeModules.release!(@desk)

    assert_equal 4, removed.size
    assert_empty Dir.children(File.join(@desk, "node_modules")), "every link into the primary is unlinked"
    primary_intact!
  end

  def test_release_unlinks_a_hand_made_whole_directory_link
    File.symlink(@modules, File.join(@desk, "node_modules"))
    assert_equal [File.join(@desk, "node_modules")], DeskNodeModules.release!(@desk)
    refute File.exist?(File.join(@desk, "node_modules"))
    primary_intact!
  end

  def test_release_leaves_a_desks_own_install_alone
    own = File.join(@desk, "node_modules", "playwright", "index.js")
    FileUtils.mkdir_p(File.dirname(own))
    File.write(own, "own\n")
    assert_empty DeskNodeModules.release!(@desk)
    assert File.file?(own), "a real install is the deleter's job, not the guard's"
    assert_empty DeskNodeModules.release!(File.join(@root, "absent")), "no desk, nothing to do"
  end

  # The hazard the guard defuses, shown on a temp tree: a trailing slash makes lstat
  # follow a directory link, so `rm -rf node_modules/` on a hand-made link empties the
  # PRIMARY. After release! the same delete touches nothing of the primary's.
  def test_the_trailing_slash_delete_that_empties_a_linked_primary_is_harmless_after_release
    File.symlink(@modules, File.join(@desk, "node_modules"))
    victim = Dir.mktmpdir("victim", @root)
    FileUtils.cp_r(File.join(@modules, "."), victim)
    File.symlink(victim, File.join(@root, "victim-link"))
    FileUtils.rm_rf(File.join(@root, "victim-link") + "/")
    assert_empty Dir.children(victim), "control: the trailing-slash delete DOES go through a link"

    DeskNodeModules.release!(@desk)
    FileUtils.rm_rf(File.join(@desk, "node_modules") + "/")
    primary_intact!
  end

  # The real deleters a teardown runs, on a real git worktree in a temp repo: the guard,
  # then `git worktree remove` (teardown_worktree), and the unwind's `--force` + rm_rf.
  def test_a_real_worktree_teardown_through_the_guard_keeps_the_primarys_node_modules
    repo = File.join(@root, "repo")
    git = ->(*args) { Open3.capture3("git", "-C", repo, *args).tap { |_o, e, s| assert s.success?, e } }
    FileUtils.mkdir_p(repo)
    git.call("init", "-q", "-b", "main")
    File.write(File.join(repo, ".gitignore"), "node_modules\n")
    File.write(File.join(repo, "package.json"), %({"name":"hub"}\n))
    File.write(File.join(repo, "package-lock.json"), LOCK)
    git.call("add", ".")
    git.call("-c", "user.name=t", "-c", "user.email=t@example.com", "commit", "-qm", "init")
    FileUtils.cp_r(@modules, File.join(repo, "node_modules"))
    @modules = File.join(repo, "node_modules")
    @sentinel = File.join(@modules, "playwright", "index.js")

    [%w[clean], %w[forced]].each do |(mode)|
      desk = File.join(repo, ".worktrees", mode)
      git.call("worktree", "add", "-q", desk, "-b", "feat/#{mode}")
      result = DeskNodeModules.plan(desk: desk, primary: repo, env: {})
      assert result.link?, result.reason
      DeskNodeModules.link!(desk: desk, source: result.source)

      DeskNodeModules.release!(desk)
      if mode == "clean"
        git.call("worktree", "remove", desk)
      else
        git.call("worktree", "remove", "--force", desk)
        FileUtils.rm_rf(desk)
      end
      refute Dir.exist?(desk)
      primary_intact!
    end
  end
end
