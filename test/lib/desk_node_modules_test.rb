  def test_a_bad_deadline_is_a_named_error_and_falls_back_to_the_default
    ["0", "-5", "abc", "1.5", "10s", "0x10", " -0 "].each do |raw|
      error = assert_raises(DeskNodeModules::InvalidDeadline, raw.inspect) { DeskNodeModules.parse_deadline(raw) }
      assert_match(/AGENT_WORKTREE_NPM_CI_DEADLINE must be a positive whole number of seconds, got #{Regexp.escape(raw.inspect)}/, error.message)

      warned = []
      seconds = DeskNodeModules.npm_ci_deadline({ "AGENT_WORKTREE_NPM_CI_DEADLINE" => raw }, warn: warned.method(:<<))
      assert_equal 600, seconds, "#{raw.inspect} falls back to the default"
      assert_equal 1, warned.size
      assert_match(/\ADeskNodeModules::InvalidDeadline: AGENT_WORKTREE_NPM_CI_DEADLINE .* using the default 600s\z/, warned.first)
    end

    silent = ->(message) { flunk "no warning expected, got #{message}" }
    assert_equal 600, DeskNodeModules.npm_ci_deadline({}, warn: silent), "unset is the default"
    assert_equal 600, DeskNodeModules.npm_ci_deadline({ "AGENT_WORKTREE_NPM_CI_DEADLINE" => " " }, warn: silent)
    assert_equal 30, DeskNodeModules.npm_ci_deadline({ "AGENT_WORKTREE_NPM_CI_DEADLINE" => "30" }, warn: silent)
    assert_equal 1, DeskNodeModules.parse_deadline(" 1 ")
  end

