  # --- the desk's own npm ci is bounded ------------------------------------------

  def test_a_hung_npm_ci_is_killed_with_its_process_group_at_the_deadline
    pidfile = File.join(@desk, "child.pid")
    hung = ["sh", "-c", "sleep 30 & echo $! > #{pidfile}; wait"]
    started = Process.clock_gettime(Process::CLOCK_MONOTONIC)
    result = DeskNodeModules.npm_ci!(@desk, deadline: 0.5, stream: nil, argv: hung)
    elapsed = Process.clock_gettime(Process::CLOCK_MONOTONIC) - started

    assert result.timed_out?, "the deadline must fire"
    refute result.success?
    assert_operator elapsed, :<, 10, "new must not wait out a hung install"
    grandchild = Integer(File.read(pidfile))
    sleep 0.2
    assert_raises(Errno::ESRCH, "the install's whole process group dies, not just npm") { Process.kill(0, grandchild) }
  end

  # Item (1): a failed or killed npm ci leaves a partial node_modules, which plan would
  # skip as "already present". install! discards it, so the next plan installs again.
  def test_a_failed_or_killed_install_discards_its_partial_node_modules_and_the_next_plan_retries
    File.write(File.join(@desk, "package-lock.json"), LOCK.sub("1.56.1", "1.56.2"))
    partial = "mkdir -p node_modules/half/lib node_modules/@sc/a && echo x > node_modules/half/lib/i.js"
    { failed: ["sh", "-c", "#{partial} && exit 1"], killed: ["sh", "-c", "#{partial} && exec sleep 30"] }.each do |mode, argv|
      assert plan.install?, plan.reason
      result = DeskNodeModules.install!(@desk, deadline: 0.5, stream: nil, argv: argv)
      refute result.success?, mode
      assert_equal mode == :killed, result.timed_out?
      refute File.exist?(File.join(@desk, "node_modules")), "#{mode}: the partial node_modules must be gone"
      assert plan.install?, "#{mode}: the next plan retries rather than skipping 'already present'"
    end
  end

  def test_discarding_a_failed_install_never_follows_a_link_into_the_primary
    File.write(File.join(@desk, "package-lock.json"), LOCK.sub("1.56.1", "1.56.2"))
    # A failure that leaves links into the primary, at every level the farm uses.
    linking = "mkdir -p node_modules/@playwright node_modules/.bin && " \
              "ln -s #{@modules}/playwright node_modules/playwright && " \
              "ln -s #{@modules}/@playwright/test node_modules/@playwright/test && " \
              "ln -s #{@modules}/.bin/playwright node_modules/.bin/playwright && exit 1"
    DeskNodeModules.install!(@desk, deadline: 10, stream: nil, argv: ["sh", "-c", linking])
    refute File.exist?(File.join(@desk, "node_modules"))
    primary_intact!

    File.symlink(@modules, File.join(@desk, "node_modules"))
    assert DeskNodeModules.discard!(@desk), "a whole-directory link is unlinked, not emptied"
    primary_intact!
  end

  def test_a_successful_install_keeps_its_node_modules
