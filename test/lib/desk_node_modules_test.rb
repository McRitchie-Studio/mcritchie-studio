# frozen_string_literal: true

# [unit] bin/lib/desk_node_modules.rb: a desk borrows the primary's node_modules only
# when package-lock.json matches byte for byte, never on Heroku or CI, and a teardown
# never deletes through a link into the primary's tree.
#
# Every tree here is a temp dir: a fake "primary" and a fake "desk". Nothing reads or
# writes a real checkout. Run directly:
#   ruby -Itest test/lib/desk_node_modules_test.rb
require "minitest/autorun"
require "fileutils"
require "open3"
require "tmpdir"
require_relative "../../bin/lib/desk_node_modules"

class DeskNodeModulesTest < Minitest::Test
  LOCK = %({"name":"hub","lockfileVersion":3,"packages":{"node_modules/playwright":{"version":"1.56.1"}}}\n)

  def setup
    @root = Dir.mktmpdir("desk-node-modules")
    @primary = File.join(@root, "primary")
    @desk = File.join(@root, "desk")
    FileUtils.mkdir_p([@primary, @desk])
    [@primary, @desk].each do |tree|
      File.write(File.join(tree, "package.json"), %({"name":"hub"}\n))
      File.write(File.join(tree, "package-lock.json"), LOCK)
    end
    git_desk!(@desk)
    # The primary's install: a package dir, a scope dir, .bin, npm's hidden lockfile,
    # and the primary's own engine tooling link (which a desk must never borrow).
    @modules = File.join(@primary, "node_modules")
    @sentinel = File.join(@modules, "playwright", "index.js")
    FileUtils.mkdir_p([File.dirname(@sentinel), File.join(@modules, "@playwright", "test"), File.join(@modules, ".bin")])
    File.write(@sentinel, "module.exports = 'primary'\n")
    File.symlink("../playwright/index.js", File.join(@modules, ".bin", "playwright"))
    File.write(File.join(@modules, "@playwright", "test", "index.js"), "// test\n")
    File.write(File.join(@modules, ".package-lock.json"), LOCK)
    @gem = File.join(@root, "gems", "studio-engine-0.116.0")
    FileUtils.mkdir_p(@gem)
    File.symlink(@gem, File.join(@modules, ".studio-engine"))
  end

  def teardown
    FileUtils.rm_rf(@root)
  end

  def plan(env: {}) = DeskNodeModules.plan(desk: @desk, primary: @primary, env: env)

  # A desk is a git checkout that ignores node_modules and .npmrc, as the hub does: the
  # script guard is written only where git ignores the .npmrc that names it.
  def git_desk!(dir, ignore: "node_modules\n/.npmrc\n")
    out, status = Open3.capture2e("git", "init", "-q", dir)
    assert status.success?, out
    File.write(File.join(dir, ".gitignore"), ignore)
  end

  def primary_intact!
    assert File.file?(@sentinel), "the primary's node_modules must survive: #{@sentinel} is gone"
    assert_equal "module.exports = 'primary'\n", File.read(@sentinel)
    assert File.file?(File.join(@modules, "@playwright", "test", "index.js"))
    assert File.symlink?(File.join(@modules, ".studio-engine")), "the primary's own engine link survives"
    assert Dir.exist?(@gem), "nothing deleted through the engine link either"
  end

  # --- plan --------------------------------------------------------------------

  def test_a_matching_lock_plans_a_link_to_the_primary
    result = plan
    assert result.link?, result.reason
    assert_equal @modules, result.source
    refute File.exist?(File.join(@desk, "node_modules")), "plan writes nothing"
  end

  def test_a_lock_that_differs_by_one_byte_plans_npm_ci_and_writes_nothing
    File.write(File.join(@desk, "package-lock.json"), LOCK.sub("1.56.1", "1.56.2"))
    result = plan
    assert result.install?, result.reason
    assert_match(/differs from the primary's/, result.reason)
    refute File.exist?(File.join(@desk, "node_modules")), "no link for a differing lock"
  end

  def test_heroku_and_ci_never_link
    [{ "DYNO" => "web.1" }, { "STACK" => "heroku-24" }].each do |env|
      assert plan(env: env).skip?, "Heroku #{env.inspect} must never link"
      assert_match(/Heroku/, plan(env: env).reason)
    end
    assert plan(env: { "CI" => "true" }).skip?, "CI installs from its own lock"
    assert plan(env: { "GITHUB_ACTIONS" => "true" }).skip?, "an Actions runner is CI"
    assert plan(env: { "CI" => "false" }).link?, "CI=false is not CI"
  end

  def test_a_desk_with_no_manifest_or_no_lock_is_skipped
    File.delete(File.join(@desk, "package-lock.json"))
    assert plan.skip?, "npm ci needs a lock; nothing to compare either"
    File.delete(File.join(@desk, "package.json"))
    assert_match(/no package\.json/, plan.reason)
  end

  def test_an_existing_desk_node_modules_is_left_alone
    FileUtils.mkdir_p(File.join(@desk, "node_modules", "playwright"))
    assert plan.skip?
    assert_match(/already present/, plan.reason)

    FileUtils.rm_rf(File.join(@desk, "node_modules"))
    File.symlink(@modules, File.join(@desk, "node_modules"))
    assert plan.skip?, "a hand-made whole-directory link is never a husk"
    File.unlink(File.join(@desk, "node_modules"))

    FileUtils.mkdir_p(File.join(@desk, "node_modules", "@scope", "pkg"))
    assert plan.skip?, "a scope holding a package is not empty, so not a husk"
  end

  # --- plan: the npm script guard must be writable -------------------------------

  def test_a_desk_that_cannot_hold_the_script_guard_installs_instead_of_linking
    npmrc = File.join(@desk, ".npmrc")
    File.write(npmrc, "registry=https://example.invalid/\n")
    assert plan.install?, "the desk's own .npmrc is never overwritten"
    assert_match(/its own \.npmrc/, plan.reason)
    File.delete(npmrc)

    File.write(File.join(@desk, ".gitignore"), "node_modules\n")
    assert plan.install?, "an unignored .npmrc would dirty the desk and make git worktree remove refuse"
    assert_match(/not ignored by git/, plan.reason)

    FileUtils.rm_rf(File.join(@desk, ".git"))
    assert plan.install?, "no git dir, nowhere to keep the guard"
    refute File.exist?(File.join(@desk, "node_modules")), "plan writes nothing"
  end

  def test_link_writes_the_guard_first_and_a_resume_reuses_its_own_npmrc
    DeskNodeModules.link!(desk: @desk, source: @modules)
    npmrc = File.read(File.join(@desk, ".npmrc"))
    guard = File.join(@desk, ".git", DeskNodeModules::GUARD)
    assert_equal "#{DeskNodeModules::NPMRC_MARK}\nscript-shell=#{guard}\n", npmrc
    assert File.executable?(guard), "npm execs the script-shell"
    out, status = Open3.capture2e("git", "-C", @desk, "status", "--porcelain")
    assert status.success?, out
    refute_match(/npmrc|#{DeskNodeModules::GUARD}/, out, "the guard dirties nothing git can see")

    DeskNodeModules.release!(@desk)
    assert plan.link?, "our own .npmrc does not block the relink: #{plan.reason}"
  end

  # --- husk: a teardown released the farm, then git refused to remove the desk ----

  def test_a_released_farm_is_a_husk_and_the_next_plan_links_it_again
    first = DeskNodeModules.link!(desk: @desk, source: @modules)
    FileUtils.mkdir_p(File.join(@desk, "node_modules", ".cache", "tool"))
    DeskNodeModules.release!(@desk)
    farm = File.join(@desk, "node_modules")
    assert_equal %w[.bin .cache @playwright], Dir.children(farm).sort, "the husk: empty containers, desk-local .cache"

    assert DeskNodeModules.husk?(farm)
    result = plan
    assert result.link?, result.reason
    assert_equal first, DeskNodeModules.link!(desk: @desk, source: result.source), "every link comes back"
    assert File.symlink?(File.join(farm, "@playwright", "test"))
    assert Dir.exist?(File.join(farm, ".cache", "tool")), "the desk's own .cache survives the relink"
    primary_intact!
  end

  # Item (2) on a real git worktree: a dirty desk makes `git worktree remove` (no
  # --force, as teardown_worktree runs it) refuse AFTER the reclaim guard unlinked the
  # farm. The resume relinks; once clean, the teardown completes.
  def test_a_refused_real_worktree_teardown_leaves_a_desk_the_resume_relinks
    repo = File.join(@root, "repo")
    git = ->(*args) { Open3.capture3("git", "-C", repo, *args) }
    ok = ->(*args) { git.call(*args).tap { |_o, e, s| assert s.success?, e } }
    git_worktree_repo!(repo, ok)
    desk = File.join(repo, ".worktrees", "dirty")
    ok.call("worktree", "add", "-q", desk, "-b", "feat/dirty")
    DeskNodeModules.link!(desk: desk, source: DeskNodeModules.plan(desk: desk, primary: repo, env: {}).source)
    File.write(File.join(desk, "work-in-progress.rb"), "# unsaved\n")

    DeskNodeModules.release!(desk)
    _out, err, status = git.call("worktree", "remove", desk)
    refute status.success?, "control: git refuses a dirty desk without --force"
    assert_match(/untracked|modified/, err)
    assert Dir.exist?(desk)

    resumed = DeskNodeModules.plan(desk: desk, primary: repo, env: {})
    assert resumed.link?, "the husk must not read as 'already present': #{resumed.reason}"
    DeskNodeModules.link!(desk: desk, source: resumed.source)
    assert_equal "module.exports = 'primary'\n", File.read(File.join(desk, "node_modules", "playwright", "index.js"))

    File.delete(File.join(desk, "work-in-progress.rb"))
    DeskNodeModules.release!(desk)
    ok.call("worktree", "remove", desk)
    refute Dir.exist?(desk)
    primary_intact!
  end

  def test_the_primary_with_no_install_or_no_lock_plans_npm_ci
    FileUtils.rm_rf(@modules)
    assert plan.install?, "nothing to borrow"
    File.delete(File.join(@primary, "package-lock.json"))
    assert_match(/primary has no package-lock\.json/, plan.reason)
  end

  def test_a_primary_whose_node_modules_is_itself_a_link_is_never_chained
    elsewhere = File.join(@root, "elsewhere")
    FileUtils.mv(@modules, elsewhere)
    File.symlink(elsewhere, @modules)
    assert plan.install?
    assert_match(/itself a link/, plan.reason)
  end

  def test_an_unfinished_primary_install_plans_npm_ci
    File.delete(File.join(@modules, ".package-lock.json"))
    assert plan.install?, "npm writes node_modules/.package-lock.json last; without it the install is unfinished"
    assert_match(/unfinished/, plan.reason)
  end

  def test_the_primary_is_never_planned_against_itself
    result = DeskNodeModules.plan(desk: @primary, primary: @primary, env: {})
    assert result.skip?, "the primary already has node_modules; it never links to itself"
  end

  # --- link! -------------------------------------------------------------------

  def test_link_builds_a_farm_of_entry_links_and_keeps_the_engine_link_desk_local
    linked = DeskNodeModules.link!(desk: @desk, source: @modules)
    farm = File.join(@desk, "node_modules")

    refute File.symlink?(farm), "the desk's node_modules is a real directory, never a link into the primary"
    assert File.directory?(farm)
    assert_equal %w[.bin/playwright @playwright/test playwright], linked

    # Directories npm writes INTO are the desk's own; only packages are links.
    %w[@playwright .bin].each do |container|
      refute File.symlink?(File.join(farm, container)), "#{container} must be a real directory in the desk"
    end
    assert_equal File.join(@modules, "playwright"), File.readlink(File.join(farm, "playwright"))
    assert_equal File.join(@modules, "@playwright", "test"), File.readlink(File.join(farm, "@playwright", "test"))
    assert_equal "../playwright/index.js", File.readlink(File.join(farm, ".bin", "playwright")),
                 "a relative bin link is recreated as itself, resolving through the desk's own package link"
    assert_equal "module.exports = 'primary'\n", File.read(File.join(farm, ".bin", "playwright")), "resolves into the primary"

    refute File.exist?(File.join(farm, ".package-lock.json")), "npm rewrites the hidden lockfile on every install"
    refute File.exist?(File.join(farm, ".studio-engine")), "the engine tooling link is each checkout's own"

    # node_tooling:link in the desk now writes the DESK's entry, not the primary's.
    File.symlink(File.join(@root, "gems", "studio-engine-0.117.0"), File.join(farm, ".studio-engine"))
    assert_equal @gem, File.readlink(File.join(@modules, ".studio-engine")), "the primary's engine link is untouched"
  end

  # --- release!: the reclaim guard ---------------------------------------------

  def test_release_removes_only_the_links_and_never_the_primarys_files
    DeskNodeModules.link!(desk: @desk, source: @modules)
    removed = DeskNodeModules.release!(@desk)

    assert_equal 3, removed.size
